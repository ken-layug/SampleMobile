using SampleMobile.Application.Abstractions;
using SampleMobile.Application.Abstractions.Identity;
using SampleMobile.Application.Abstractions.Messaging;
using SampleMobile.Application.Abstractions.Push;
using SampleMobile.Application.Abstractions.Repositories;
using SampleMobile.Application.Common;
using SampleMobile.Application.Services;
using SampleMobile.Domain.Entities;

namespace SampleMobile.Application.Features.Simulation;

public enum SimulatedScenario {
    /// <summary>The simulator accepts the first attempt.</summary>
    Accept,

    /// <summary>Two transient failures, then acceptance: exercises backoff and retry.</summary>
    TransientThenAccept,

    /// <summary>A permanent failure: no retries.</summary>
    PermanentFailure,

    /// <summary>The simulator reports the address as invalid: the virtual device gets disabled.</summary>
    InvalidRegistration
}

public sealed record RunSimulatedScenarioCommand(Guid RecipientUserId, SimulatedScenario Scenario)
    : ICommand<OperationResult<SimulatedScenarioRun>>;

public sealed record SimulatedScenarioRun(Guid NotificationId, Guid RegistrationId, Guid? DeliveryJobId);

/// <summary>
/// Runs one end-to-end delivery scenario against the simulated provider. Each run gets its own fresh
/// virtual device, so an "invalid registration" run never disables the seeded demo device.
/// Everything after this handler is the real pipeline: delivery worker, retry policy, attempt history.
/// </summary>
public sealed class RunSimulatedScenarioCommandHandler(
    ISimulatedPushControl simulator,
    IDeviceRegistrationRepository registrations,
    INotificationPublisher publisher,
    IIdentityService identity,
    IUnitOfWork unitOfWork,
    TimeProvider timeProvider) : ICommandHandler<RunSimulatedScenarioCommand, OperationResult<SimulatedScenarioRun>> {

    public async Task<OperationResult<SimulatedScenarioRun>> HandleAsync(
        RunSimulatedScenarioCommand command, CancellationToken cancellationToken = default) {
        if (await identity.FindByIdAsync(command.RecipientUserId, cancellationToken) is null) {
            return OperationResult<SimulatedScenarioRun>.Invalid("recipientUserId", "The recipient does not exist.");
        }

        var runId = Guid.CreateVersion7().ToString("N");
        var address = $"sim-{command.Scenario.ToString().ToLowerInvariant()}-{runId}";
        var registration = DeviceRegistration.Register(
            command.RecipientUserId,
            $"sim-scenario-{runId[^12..]}",
            DevicePlatform.Virtual,
            simulator.ProviderId,
            address,
            timeProvider.GetUtcNow());

        // Script before anything is persisted, so the worker can never dispatch ahead of the script.
        simulator.ScriptOutcomes(address, ScriptFor(command.Scenario));

        registrations.Add(registration);
        await unitOfWork.SaveChangesAsync(cancellationToken);

        var published = await publisher.PublishAsync(
            new NotificationIntent(
                Type: NotificationTypes.DemoSimulation,
                Title: $"Simulator: {Describe(command.Scenario)}",
                Body: "Generated by the simulated-provider test page. No real device is involved.",
                RecipientUserIds: [command.RecipientUserId],
                Metadata: new Dictionary<string, string> { ["scenario"] = command.Scenario.ToString() },
                TargetRegistrationIds: [registration.Id]),
            cancellationToken);

        if (!published.Succeeded) {
            return OperationResult<SimulatedScenarioRun>.FromFailure(published);
        }

        var jobIds = published.Value!.DeliveryJobIds;
        return OperationResult<SimulatedScenarioRun>.Success(new SimulatedScenarioRun(
            published.Value.NotificationId,
            registration.Id,
            jobIds.Count > 0 ? jobIds[0] : null));
    }

    public static string Describe(SimulatedScenario scenario) =>
        scenario switch {
            SimulatedScenario.Accept => "accepted on first attempt",
            SimulatedScenario.TransientThenAccept => "transient failures, then retry succeeds",
            SimulatedScenario.PermanentFailure => "permanent failure",
            SimulatedScenario.InvalidRegistration => "invalid device registration",
            _ => scenario.ToString()
        };

    private static IReadOnlyList<DispatchOutcome> ScriptFor(SimulatedScenario scenario) =>
        scenario switch {
            SimulatedScenario.Accept => [],
            SimulatedScenario.TransientThenAccept => [DispatchOutcome.TransientFailure, DispatchOutcome.TransientFailure],
            SimulatedScenario.PermanentFailure => [DispatchOutcome.PermanentFailure],
            SimulatedScenario.InvalidRegistration => [DispatchOutcome.InvalidRegistration],
            _ => throw new ArgumentOutOfRangeException(nameof(scenario), scenario, null)
        };
}
